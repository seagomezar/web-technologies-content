"""Compile the authored locale catalogs for offline use; never fetch at runtime."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
locales={lang:json.loads((root/f'locales/{lang}.json').read_text(encoding='utf-8')) for lang in ('en','es')}
patterns=json.loads((root/'locales/patterns.json').read_text(encoding='utf-8'))
talk=json.loads((root/'locales/talk.en.json').read_text(encoding='utf-8'))
(root/'locale-data.js').write_text('/* Generated by scripts/build-locales.py. */\nwindow.LOCALES='+json.dumps(locales,ensure_ascii=False)+';\nwindow.LOCALE_PATTERNS='+json.dumps(patterns,ensure_ascii=False)+';\nwindow.TALK_EN='+json.dumps(talk,ensure_ascii=False)+';\n',encoding='utf-8')
print('Compiled English and Spanish catalogs and the complete English talk script.')
